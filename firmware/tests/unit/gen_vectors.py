#!/usr/bin/env python3
"""Generates src/vectors.h: byte-exact fixtures from tools/owlproto.py.

The firmware tests compare their own encoders against these bytes, so the C
code and the Python reference implementation cannot drift apart silently.

Regenerate (from the repo root) after changing the protocol:
    python3 firmware/tests/unit/gen_vectors.py > firmware/tests/unit/src/vectors.h
"""

import os
import sys
import zlib

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "..", "tools"))
import owlproto as p  # noqa: E402


def c_array(name: str, data: bytes) -> str:
    body = ", ".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[] = {{{body}}};\n"


def main() -> None:
    out = [
        "/* Generated by firmware/tests/unit/gen_vectors.py from tools/owlproto.py. Do not edit.\n",
        " *   python3 firmware/tests/unit/gen_vectors.py > firmware/tests/unit/src/vectors.h\n",
        " */\n",
        "#include <stdint.h>\n\n",
    ]

    status = p.Status((0, 3, 0), 3850, p.FLAG_RECORDING | p.FLAG_STORAGE_LOW, 1024, 16380, 5, 42)
    out.append(c_array("vec_status", status.pack()))

    hdr = p.SegmentHeader(p.SEG_TYPE_AUDIO, p.CODEC_OPUS, 20, 99, 3, 600_000, 16000, 1, 1234)
    out.append(c_array("vec_seg_header_audio", hdr.pack()))

    frames = [bytes([0x11] * 3), bytes(range(40)), b"\xfc\xff\xfe"]
    ahdr = p.SegmentHeader(p.SEG_TYPE_AUDIO, p.CODEC_OPUS, 20, 7, 2, 123_456_789_012, 16000, 1, 0)
    audio = p.build_audio_segment(ahdr, frames)
    out.append(c_array("vec_audio_segment", audio))
    out.append(f"#define VEC_AUDIO_SEGMENT_CRC 0x{zlib.crc32(audio) & 0xffffffff:08x}u\n")

    events = [
        (1_000, p.EVT_BOOKMARK, 0),
        (2_000, p.EVT_RECORDING_OFF, p.CAUSE_BUTTON),
        (3_000, p.EVT_RECORDING_ON, p.CAUSE_APP),
        (0x1_0000_0001, p.EVT_POWER_OFF, p.CAUSE_BATTERY),
    ]
    ehdr = p.SegmentHeader(p.SEG_TYPE_EVENTS, p.CODEC_PCM16, 0, 12, 3, 500, 16000, 1, 0)
    out.append(c_array("vec_event_segment", p.build_event_segment(ehdr, events)))

    entries = [(1, p.SEG_TYPE_AUDIO, 1000), (2, p.SEG_TYPE_EVENTS, 52), (0xDEADBEEF, 1, 0x123456)]
    out.append(c_array("vec_list_payload", p.build_list_segments(entries)))

    out.append(c_array("vec_req_time_sync", p.time_sync_request(9, 1_700_000_000_123, -540)))
    out.append(c_array("vec_req_list", p.list_segments_request(1, 0, 26)))
    out.append(c_array("vec_req_fetch", p.fetch_segment_request(2, 7, 472)))
    out.append(c_array("vec_req_ack", p.ack_segment_request(3, 7, 0x12345678)))
    out.append(c_array("vec_req_set_recording_on", p.set_recording_request(4, True)))
    out.append(c_array("vec_req_set_recording_off", p.set_recording_request(5, False)))
    out.append(c_array("vec_req_unpair", p.unpair_request(4)))

    ts = p.Response(p.OP_TIME_SYNC, 9, p.RESULT_OK, (3).to_bytes(4, "little") + (5000).to_bytes(8, "little"))
    out.append(c_array("vec_resp_time_sync", ts.pack()))

    blob = bytes(range(256)) * 2
    chunks = list(p.chunk_segment(7, blob, start=236))
    out.append(c_array("vec_data_chunk_236", chunks[0]))

    out.append(f"#define VEC_DATA_CHUNK_MAX {p.DATA_CHUNK_MAX}\n")
    out.append(f"#define VEC_LIST_MAX {p.LIST_MAX_PER_RESPONSE}\n")
    out.append(f"#define VEC_FLAG_PAIRING_OPEN 0x{p.FLAG_PAIRING_OPEN:02x}u\n")
    out.append(f"#define VEC_PAIRING_WINDOW_MS {p.PAIRING_WINDOW_MS}\n")
    out.append(f"#define VEC_UNENCRYPTED_TIMEOUT_MS {p.UNENCRYPTED_TIMEOUT_MS}\n")
    out.append(f"#define VEC_CRC_123456789 0x{zlib.crc32(b'123456789') & 0xffffffff:08x}u\n")
    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main()
